-- ===========================================================================
-- 15-uploads.sql - the upload log, which is audit evidence.
-- ===========================================================================
--
-- UPLOAD_LOG in the spreadsheet, called "the audit evidence trail" where its
-- columns are defined in Config.gs. One row per upload, written when the
-- upload opens and closed when it finishes.
--
-- IT IS NOT A LIST OF FILES. It is the answer to "where did this figure come
-- from", asked weeks later by somebody who was not there. Who uploaded it,
-- when, which files, which date range, how many rows went in and how many
-- were already known. Deleting an upload uses it to find the tickets that
-- came in on those files and no others - see deleteUpload in api/uploads.js -
-- so a row here is not decoration, it is how the delete knows what to remove.
--
-- WHY upload_id IS THE PRIMARY KEY AND NOT A SERIAL
--
-- The ID is generated by the API as 'UPL-20260916-103455-a1b2' and travels
-- to the browser, which then sends it back on every batch. A serial would
-- mean the browser holding a number that means nothing outside this database
-- and that would collide with a restored backup's numbering. Ingest.gs made
-- the same choice, and records why the four random characters are there:
--
--     "Seconds are not unique enough. Two uploads started in the same second
--      used to share an ID, and deleting one then found two matching log
--      rows and removed a single one - so the row appeared to survive being
--      deleted."
--
-- PRIMARY KEY makes that structural rather than hoped for: two uploads
-- cannot share an ID, because the database will not have it.
--
-- PERMISSIONS: none granted here. See the note in 14-backup.sql.
-- ===========================================================================


CREATE TABLE IF NOT EXISTS upload_run (
  -- 'UPL-20260916-103455-a1b2'. Generated by the API, held by the browser
  -- for the length of the upload, and quoted in the history afterwards.
  upload_id     text         PRIMARY KEY,

  uploaded_at   timestamptz  NOT NULL DEFAULT now(),

  -- WHO, taken from the signed token and not from the browser. Ingest.gs:
  -- "It used to be Session.getActiveUser().getEmail(), and on this
  -- deployment that is always the empty string ... Every upload in the
  -- history therefore said 'unknown'".
  uploaded_by   text         NOT NULL DEFAULT '',

  -- The three ' | ' separated lists, stored exactly as the sheet stored
  -- them. NOT split into a child table, and that is deliberate: file_names
  -- is matched against ticket.source_files, which is itself a ' | ' list
  -- written by the merge, and the two have to be the same shape or the
  -- delete cannot line them up. One normalised and one not would be worse
  -- than neither.
  file_names    text         NOT NULL DEFAULT '',
  report_types  text         NOT NULL DEFAULT '',
  departments   text         NOT NULL DEFAULT '',

  -- How many rows the browser said it was sending, how many were new, and
  -- how many already existed and were updated by the merge.
  --
  -- THESE TWO MEAN SOMETHING DIFFERENT FROM THE SHEET'S VERSION, and it is
  -- worth being honest about it. finishUpload in Ingest.gs wrote the result
  -- of compactTickets into these columns - the number of unique tickets left
  -- in the WHOLE SHEET and the number of duplicates collapsed across all of
  -- it. Those are facts about the tab, not about the upload, and on the
  -- history screen beside one upload's filename they read as though they
  -- were. Here the ON CONFLICT merge reports per row whether it inserted or
  -- updated, so these are counts of THIS upload. Same columns, same screen,
  -- and now the numbers answer the question the heading asks.
  rows_in_file  integer      NOT NULL DEFAULT 0,
  rows_added    integer      NOT NULL DEFAULT 0,
  rows_updated  integer      NOT NULL DEFAULT 0,

  -- The date range the files covered. date and not text.
  --
  -- The sheet forced these two columns to plain text with
  -- setNumberFormat('@') before writing, because "Left alone, Sheets parses
  -- '2026-08-01' into a Date and hands it back as 'Sat Aug 01 2026 00:00:00
  -- GMT+0600'". That fight does not exist here: a PostgreSQL date has no
  -- time and no timezone, and comes back as 2026-08-01 because that is what
  -- it is. dayString() in Ingest.gs, which existed only to cope with reading
  -- back both shapes, has no port for the same reason.
  date_from     date,
  date_to       date,

  -- 'in progress' until finishUpload closes it, then 'complete'. A row that
  -- still says 'in progress' an hour later is an upload whose browser tab
  -- was closed half way, and the history screen should show that rather
  -- than hide it.
  notes         text         NOT NULL DEFAULT ''
);


-- The history screen asks for "the most recent uploads" and nothing else.
CREATE INDEX IF NOT EXISTS upload_run_at_idx
  ON upload_run (uploaded_at DESC);


-- ===========================================================================
-- WHAT IS NOT HERE
-- ===========================================================================
--
-- No foreign key from ticket to upload_run. A ticket can carry source files
-- from several uploads - that is the whole point of the merge - so the
-- relationship is many to many through a text list, and a foreign key would
-- be a lie about the shape of the data. The delete reasons about the list
-- instead, and only removes a ticket when EVERY file it came from belonged
-- to the upload being deleted.
--
-- No ON DELETE CASCADE, for the same reason. Deleting an upload must not
-- delete a ticket that another upload also vouched for; Ingest.gs is clear
-- that "Deleting them outright would silently remove data the user never
-- asked to lose".
-- ===========================================================================
